export function parseSwimTime(text) {
  if (!text) return null;
  const match = String(text).trim().match(/^(?:(\d+):)?(\d{1,2}(?:\.\d+)?)$/);
  if (!match) return null;
  const minutes = match[1] ? Number(match[1]) : 0;
  return minutes * 60 + Number(match[2]);
}

export function formatSwimTime(seconds) {
  if (seconds == null || !Number.isFinite(seconds)) return "";
  const minutes = Math.floor(seconds / 60);
  const rest = (seconds - minutes * 60).toFixed(2).padStart(5, "0");
  return minutes > 0 ? `${minutes}:${rest}` : rest;
}

function standardMeta(id) {
  return STANDARD_META.find((standard) => standard.id === id);
}

// Flattened one record per (standard, age group, gender, course, event) with a
// non-null time. Built once at module load.
const RECORDS = STANDARDS.flatMap((standard) => {
  const meta = standardMeta(standard.id);
  return standard.sections.flatMap((section) => section.rows.flatMap((row) => {
    const [stroke, scyDistance, lcDistance, gLCM, gSCM, gSCY, bSCY, bSCM, bLCM] = row;
    const cells = [
      { gender: "girls", course: "LCM", distance: lcDistance, timeText: gLCM },
      { gender: "girls", course: "SCM", distance: lcDistance, timeText: gSCM },
      { gender: "girls", course: "SCY", distance: scyDistance, timeText: gSCY },
      { gender: "boys", course: "SCY", distance: scyDistance, timeText: bSCY },
      { gender: "boys", course: "SCM", distance: lcDistance, timeText: bSCM },
      { gender: "boys", course: "LCM", distance: lcDistance, timeText: bLCM },
    ];
    return cells
      .filter((cell) => cell.timeText != null && cell.distance != null)
      .map((cell) => ({
        standardId: standard.id,
        standardName: meta.name,
        color: meta.color,
        sourceUrl: SOURCE_URLS[standard.id],
        ageGroupLabel: section.ageGroupLabel,
        minAge: section.minAge,
        maxAge: section.maxAge,
        stroke,
        gender: cell.gender,
        course: cell.course,
        distance: cell.distance,
        timeText: cell.timeText,
        seconds: parseSwimTime(cell.timeText),
      }));
  }));
});

/** Every standard whose age range covers `age`, in the fixed display/color order. */
export function standardsForAge(age) {
  const seen = new Set();
  const matches = [];
  for (const record of RECORDS) {
    if (age < record.minAge || (record.maxAge != null && age > record.maxAge)) continue;
    if (seen.has(record.standardId)) continue;
    seen.add(record.standardId);
    matches.push({ id: record.standardId, name: record.standardName, color: record.color, sourceUrl: record.sourceUrl });
  }
  return STANDARD_META.filter((standard) => seen.has(standard.id))
    .map((standard) => matches.find((match) => match.id === standard.id));
}

/**
 * Qualifying times for one swimmer profile, grouped by standard, for charting.
 * Returns one series per applicable standard, each with one point per distance
 * that standard contests for this stroke/gender/course/age.
 */
export function getQualifyingSeries({ age, gender, stroke, course }) {
  const matches = RECORDS.filter((record) =>
    record.gender === gender
    && record.stroke === stroke
    && record.course === course
    && age >= record.minAge
    && (record.maxAge == null || age <= record.maxAge));
  const byStandard = new Map();
  for (const record of matches) {
    if (!byStandard.has(record.standardId)) {
      byStandard.set(record.standardId, {
        id: record.standardId,
        name: record.standardName,
        color: record.color,
        sourceUrl: record.sourceUrl,
        ageGroupLabel: record.ageGroupLabel,
        points: [],
      });
    }
    byStandard.get(record.standardId).points.push({
      distance: record.distance,
      seconds: record.seconds,
      timeText: record.timeText,
    });
  }
  for (const series of byStandard.values()) series.points.sort((a, b) => a.distance - b.distance);
  return STANDARD_META
    .filter((standard) => byStandard.has(standard.id))
    .map((standard) => byStandard.get(standard.id));
}

